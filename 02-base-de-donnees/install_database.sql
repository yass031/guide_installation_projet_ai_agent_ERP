-- ----------------------------------------------------------------
-- fn_sale_payment_alerts
-- Alerte par vente : compare sale_date à aujourd'hui.
-- Ventes totalement soldées = exclues.
-- Sinon, au-delà du seuil de jours, message adapté :
--   - rien payé du tout
--   - payé partiellement, il reste un solde
-- ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION agent_reporting.fn_sale_payment_alerts(threshold_days integer DEFAULT 30)
 RETURNS TABLE(sale_id bigint, sale_reference text, client_id bigint, client_name text, client_phone text, sale_date timestamp without time zone, days_elapsed integer, net_total numeric, total_paid numeric, remaining_balance numeric, alert_type text, alert_message text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH sale_payments AS (
        SELECT
            sd.sale_id,
            sd.sale_reference::text                                  AS sale_reference,
            sd.client_id,
            sd.client_name::text                                     AS client_name,
            sd.client_phone::text                                    AS client_phone,
            sd.sale_date,
            sd.net_total,
            COALESCE(SUM(pa.amount_applied), 0)                    AS total_paid,
            (CURRENT_DATE - sd.sale_date::date)                     AS days_elapsed
        FROM agent_reporting.v_sales_detail sd
        LEFT JOIN payment_allocations pa
            ON pa.payable_id = sd.sale_id
            AND pa.payable_type LIKE '%Sale'
        LEFT JOIN payments p
            ON p.id = pa.payment_id
            AND p.status = 'approved'
        GROUP BY sd.sale_id, sd.sale_reference, sd.client_id, sd.client_name, sd.client_phone, sd.sale_date, sd.net_total
    )
    SELECT
        sp.sale_id,
        sp.sale_reference,
        sp.client_id,
        sp.client_name,
        sp.client_phone,
        sp.sale_date,
        sp.days_elapsed,
        sp.net_total,
        sp.total_paid,
        sp.net_total - sp.total_paid                                AS remaining_balance,
        CASE
            WHEN sp.total_paid = 0 THEN 'unpaid'
            ELSE 'partial'
        END                                                          AS alert_type,
        CASE
            WHEN sp.total_paid = 0
                THEN 'Le client n''a rien payé pour la vente ' || sp.sale_reference
                     || ' et ' || sp.days_elapsed || ' jours sont passés depuis la vente (total dû : '
                     || sp.net_total || ' MAD).'
            ELSE
                'Le client a payé ' || sp.total_paid || ' MAD pour la vente ' || sp.sale_reference
                || ', il reste ' || (sp.net_total - sp.total_paid) || ' MAD, et '
                || sp.days_elapsed || ' jours sont passés depuis la vente.'
        END                                                          AS alert_message
    FROM sale_payments sp
    WHERE sp.net_total - sp.total_paid > 0
      AND sp.days_elapsed >= threshold_days
    ORDER BY sp.days_elapsed DESC;
END;
$function$;

-- ---- [55/64] products_stock/recommandation/fn_products_to_discontinue.sql
CREATE OR REPLACE FUNCTION agent_reporting.fn_products_to_discontinue(
    p_dormant_days_threshold INT DEFAULT 90,
    p_days_lookback INT DEFAULT 90
)
RETURNS TABLE (
    product_id BIGINT,
    product_name VARCHAR,
    current_stock NUMERIC,
    product_price NUMERIC,
    avg_purchase_price NUMERIC,
    margin NUMERIC,
    avg_daily_sales NUMERIC,
    days_since_last_sale INT,
    discontinue_reason TEXT
)
AS $$
    WITH sales_velocity AS (
        SELECT 
            si.product_id,
            SUM(si.ordered_quantity)::NUMERIC / p_days_lookback AS avg_daily_sales,
            MAX(s.sale_date) AS last_sale_date
        FROM agent_reporting.v_sale_items si
        JOIN agent_reporting.v_sales_detail s ON si.sale_id = s.sale_id
        WHERE s.sale_date >= NOW() - make_interval(days => p_days_lookback)
        GROUP BY si.product_id
    ),
    purchase_cost AS (
        SELECT 
            pi.product_id,
            AVG(pi.price) AS avg_purchase_price
        FROM agent_reporting.v_purchase_items pi
        GROUP BY pi.product_id
    )
    SELECT 
        p.product_id,
        p.product_name,
        p.current_stock,
        p.product_price,
        pc.avg_purchase_price,
        (p.product_price - pc.avg_purchase_price) AS margin,
        COALESCE(sv.avg_daily_sales, 0),
        CASE 
            WHEN sv.last_sale_date IS NOT NULL 
            THEN EXTRACT(DAY FROM NOW() - sv.last_sale_date)::INT
            ELSE NULL
        END AS days_since_last_sale,
        CASE
            WHEN (p.product_price - pc.avg_purchase_price) < 0 
                 AND COALESCE(sv.avg_daily_sales, 0) = 0 
                THEN 'Marge négative ET stock dormant'
            WHEN (p.product_price - pc.avg_purchase_price) < 0 
                THEN 'Marge négative'
            ELSE 'Stock dormant'
        END AS discontinue_reason
    FROM agent_reporting.v_products_catalog p
    LEFT JOIN sales_velocity sv ON sv.product_id = p.product_id
    LEFT JOIN purchase_cost pc ON pc.product_id = p.product_id
    WHERE pc.avg_purchase_price IS NOT NULL
      AND (
          (p.product_price - pc.avg_purchase_price) < 0
          OR sv.avg_daily_sales IS NULL
          OR (sv.last_sale_date IS NOT NULL AND sv.last_sale_date < NOW() - make_interval(days => p_dormant_days_threshold))
      )
    ORDER BY margin ASC NULLS LAST;
$$ LANGUAGE sql STABLE;

