-- ---- [27/64] products_stock/traitement/fn_stock_report_core.sql
CREATE OR REPLACE FUNCTION agent_reporting.fn_stock_report_core(p_product_id bigint, p_only_below_alert boolean, p_days_lookback integer, p_target_coverage_days integer)
 RETURNS TABLE(product_id bigint, product_reference character varying, product_name character varying, current_stock numeric, alert_stock_threshold numeric, avg_daily_sales numeric, days_until_stockout numeric, suggested_reorder_qty numeric)
 LANGUAGE sql

AS $function$
    WITH sales_velocity AS (
        SELECT 
            si.product_id,
            SUM(si.ordered_quantity)::NUMERIC / p_days_lookback AS avg_daily_sales
        FROM agent_reporting.v_sale_items si
        JOIN agent_reporting.v_sales_detail s ON si.sale_id = s.sale_id
        WHERE s.sale_date >= NOW() - make_interval(days => p_days_lookback)
        GROUP BY si.product_id
    )

    SELECT 
        p.product_id AS product_id,
        p.product_reference AS product_reference,
        p.product_name AS product_name,
        p.current_stock AS current_stock,
        p.alert_stock_threshold AS alert_stock_threshold,
        COALESCE(sv.avg_daily_sales, 0) AS avg_daily_sales,
        CASE 
            WHEN COALESCE(sv.avg_daily_sales, 0) > 0 
            THEN ROUND(p.current_stock / sv.avg_daily_sales, 1)
            ELSE NULL
        END AS days_until_stockout,
        CASE 
            WHEN COALESCE(sv.avg_daily_sales, 0) > 0 
            THEN GREATEST(ROUND((sv.avg_daily_sales * p_target_coverage_days) - p.current_stock, 0), 0)
            ELSE 0
        END AS suggested_reorder_qty
    FROM agent_reporting.v_products_catalog p
    LEFT JOIN sales_velocity sv ON sv.product_id = p.product_id
    WHERE (p_product_id IS NULL OR p.product_id = p_product_id)
      AND (p_only_below_alert = FALSE OR p.current_stock <= p.alert_stock_threshold)
    ORDER BY days_until_stockout ASC NULLS LAST;
$function$;

