-- ----------------------------------------------------------------------
-- Outil de contrôle (ne pas modifier) : bloque l'installation si une valeur
-- de l'étape 0 n'a pas été remplie.
-- ----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION pg_temp.nx(k text) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE v text;
BEGIN
    v := current_setting('nextact.' || k, true);
    IF v IS NULL OR btrim(v) = '' OR v LIKE 'CHANGE_ME%' THEN
        RAISE EXCEPTION 'La valeur "%" n''est pas renseignée. Retournez à l''ÉTAPE 0, remplacez les CHANGE_ME puis exécutez-la de nouveau (dans le même Query Tool).', k;
    END IF;
    RETURN v;
END $$;

-- Vérification : doit afficher 7 lignes, aucune ne doit commencer par CHANGE_ME
