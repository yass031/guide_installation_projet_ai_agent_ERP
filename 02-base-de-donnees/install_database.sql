-- ---- [57/64] purchases-suppliers/recommandation/fn_best_supplier_for_product.sql
CREATE OR REPLACE FUNCTION agent_reporting.fn_best_supplier_for_product(
    p_product_id BIGINT DEFAULT NULL,
    p_product_name VARCHAR DEFAULT NULL
)
RETURNS TABLE (
    supplier_id BIGINT,
    supplier_name VARCHAR,
    avg_price NUMERIC,
    purchase_count BIGINT,
    last_purchase_date TIMESTAMP,
    recommendation_score NUMERIC
)
AS $$
    SELECT 
        s.id AS supplier_id,
        s.name AS supplier_name,
        AVG(pi.price) AS avg_price,
        COUNT(*)::BIGINT AS purchase_count,
        MAX(p.created_at) AS last_purchase_date,
        (
            (1 / NULLIF(AVG(pi.price), 0)) * 0.8 
            + (COUNT(*)::NUMERIC / 100) * 0.2
        ) AS recommendation_score
    FROM agent_reporting.v_purchase_items pi
    JOIN agent_reporting.v_purchases p ON pi.purchase_id = p.id
    JOIN agent_reporting.v_suppliers s ON p.supplier_id = s.id
    JOIN agent_reporting.v_products_catalog pc ON pi.product_id = pc.product_id
    WHERE
        (p_product_id IS NOT NULL AND pi.product_id = p_product_id)
        OR
        (p_product_id IS NULL AND p_product_name IS NOT NULL AND pc.product_name ILIKE p_product_name)
    GROUP BY s.id, s.name
    ORDER BY recommendation_score DESC NULLS LAST;
$$ LANGUAGE sql STABLE;

