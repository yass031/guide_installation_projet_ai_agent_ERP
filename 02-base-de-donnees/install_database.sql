-- ---- [7/64] payments/consultation/v_payments_detail.sql
-- ============================================================
-- VUE 1 : v_payments_detail
-- Granularité = 1 ligne par tranche versée (payment_allocations)
-- Objectif : détail complet vente + client + paiement + tranche,
-- avec solde restant calculé, pour un usage riche par l'agent IA
-- ============================================================
CREATE OR REPLACE VIEW agent_reporting.v_payments_detail AS
SELECT
    pa.id                                          AS allocation_id,
    p.id                                            AS payment_id,
    p.reference                                     AS payment_reference,
    p.method,
    p.status                                        AS payment_status,
    p.external_reference,
    p.stripe_intent_id,
    p.notes                                         AS payment_notes,

    -- Vente résolue (payments.sale_id en priorité, sinon payment_allocations.payable_id)
    sd.sale_id,
    sd.sale_reference,
    sd.status                                       AS sale_status,
    sd.sale_date,

    -- Client (déjà dans v_sales_detail)
    sd.client_id,
    sd.client_name,
    sd.client_email,
    sd.client_phone,
    sd.client_address,

    -- Montants de la vente
    sd.subtotal,
    sd.tax_rate,
    sd.tax_amount,
    sd.discount_amount,
    sd.gross_total,
    sd.refunded_total,
    sd.net_total,

    -- Détail de la tranche versée
    pa.amount_applied,
    pa.created_at                                   AS allocation_date,

    -- Cumul et solde restant sur la vente (toutes tranches confondues)
    SUM(pa.amount_applied) OVER (PARTITION BY sd.sale_id)          AS total_applied_on_sale,
    sd.net_total - SUM(pa.amount_applied) OVER (PARTITION BY sd.sale_id) AS remaining_balance,

    p.created_at                                    AS payment_created_at,
    p.updated_at                                     AS payment_updated_at

FROM payments p
JOIN payment_allocations pa
    ON pa.payment_id = p.id
    AND pa.payable_type = 'App\\Models\\Sale'   -- deux backslashs tapés = deux backslashs stockés
JOIN agent_reporting.v_sales_detail sd
    ON sd.sale_id = COALESCE(p.sale_id, pa.payable_id)
ORDER BY p.id, pa.created_at;

