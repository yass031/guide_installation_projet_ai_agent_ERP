-- ---- [41/64] refunds/traitement/fn_refund_rate_by_product.sql
-- fn_refund_rate_by_product : taux de retour = refund_quantity / quantity vendue
CREATE OR REPLACE FUNCTION agent_reporting.fn_refund_rate_by_product(
    p_start_date date DEFAULT NULL,
    p_end_date   date DEFAULT NULL
)
RETURNS TABLE (
    product_id        int,
    product_name      text,
    quantity_sold     numeric,
    quantity_refunded numeric,
    refund_rate_pct   numeric
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        p.id,
        p.name,
        COALESCE(SUM(si.quantity), 0)           AS quantity_sold,
        COALESCE(SUM(si.refund_quantity), 0)    AS quantity_refunded,
        CASE
            WHEN COALESCE(SUM(si.quantity), 0) = 0 THEN 0
            ELSE ROUND(
                100.0 * COALESCE(SUM(si.refund_quantity), 0)
                / NULLIF(SUM(si.quantity), 0), 2
            )
        END AS refund_rate_pct
    FROM products p
    JOIN sale_items si ON si.product_id = p.id
    JOIN sales s        ON s.id = si.sale_id
    WHERE (p_start_date IS NULL OR s.created_at >= p_start_date)
      AND (p_end_date   IS NULL OR s.created_at <  p_end_date + INTERVAL '1 day')
    GROUP BY p.id, p.name
    ORDER BY refund_rate_pct DESC;
$$;

