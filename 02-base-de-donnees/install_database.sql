-- ---- [59/64] sales/recommandation/fn_sales_alert_decline.sql
CREATE OR REPLACE FUNCTION agent_reporting.fn_sales_alert_decline(
    p_current_start DATE,
    p_current_end DATE,
    p_previous_start DATE,
    p_previous_end DATE,
    p_threshold_pct NUMERIC DEFAULT 20
)
RETURNS TABLE(
    product_id BIGINT,
    product_reference VARCHAR,
    product_name VARCHAR,
    previous_qty NUMERIC,
    current_qty NUMERIC,
    variation_pct NUMERIC,
    alert_level VARCHAR
)
LANGUAGE SQL
AS $$

WITH previous_period AS (
    SELECT
        product_id,
        product_reference,
        product_name,
        SUM(net_quantity_sold) AS qty
    FROM agent_reporting.v_sale_items
    WHERE sale_date::date BETWEEN p_previous_start AND p_previous_end
    GROUP BY product_id, product_reference, product_name
),

current_period AS (
    SELECT
        product_id,
        SUM(net_quantity_sold) AS qty
    FROM agent_reporting.v_sale_items
    WHERE sale_date::date BETWEEN p_current_start AND p_current_end
    GROUP BY product_id
)

SELECT
    p.product_id,
    p.product_reference,
    p.product_name,
    p.qty AS previous_qty,
    COALESCE(c.qty, 0) AS current_qty,
    ROUND(
        (COALESCE(c.qty, 0) - p.qty) / p.qty * 100
    , 2) AS variation_pct,
    CASE
        WHEN ROUND((COALESCE(c.qty, 0) - p.qty) / p.qty * 100, 2) <= -60 THEN 'HIGH'
        WHEN ROUND((COALESCE(c.qty, 0) - p.qty) / p.qty * 100, 2) <= -40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS alert_level

FROM previous_period p
LEFT JOIN current_period c ON p.product_id = c.product_id

WHERE p.qty > 0
AND ROUND((COALESCE(c.qty, 0) - p.qty) / p.qty * 100, 2) <= -p_threshold_pct

ORDER BY variation_pct ASC;

$$;

-- ---- [60/64] aletre_email.sql
-- ================================================================
-- fn_get_all_active_alerts
-- Agrège toutes les fonctions de recommandation "alertes" en un
-- format unifié (alert_type, alert_key, alert_message, severity)
-- pour être scanné par le job périodique d'envoi d'email.
--
-- EXCLUES volontairement :
--   - fn_cashflow_forecast    -> pas une alerte discrète (1 ligne systématique)
--   - fn_best_supplier_for_product -> nécessite un product_id, outil à la demande
-- ================================================================
CREATE OR REPLACE FUNCTION agent_reporting.fn_get_all_active_alerts()
RETURNS TABLE (
    alert_type    text,
    alert_key     text,
    alert_message text,
    severity      text
)
LANGUAGE plpgsql
STABLE
AS $$
BEGIN
    RETURN QUERY

    -- 1. Clients à relancer (inactivité)
    SELECT
        'client_recontact'::text,
        r.client_id::text,
        'Client à relancer : ' || r.client_name || ' (inactif depuis le '
            || COALESCE(r.last_sale_date::text, 'jamais acheté')
            || ', total historique : ' || r.total_spent || ' MAD).',
        CASE WHEN r.total_spent >= 5000 THEN 'high' ELSE 'medium' END
    FROM agent_reporting.fn_clients_to_recontact() r

    UNION ALL

    -- 2. Devis sur le point d'expirer
    SELECT
        'devis_expire',
        d.devis_id::text,
        'Devis ' || d.devis_reference || ' (client : ' || d.client_name
            || ') expire dans ' || d.days_until_expiry || ' jour(s), montant : '
            || d.total || ' MAD.',
        CASE WHEN d.days_until_expiry <= 1 THEN 'high' ELSE 'medium' END
    FROM agent_reporting.fn_devis_about_to_expire() d

    UNION ALL

    -- 3. Devis envoyés sans relance
    SELECT
        'devis_followup',
        d.devis_id::text,
        'Devis ' || d.devis_reference || ' (client : ' || d.client_name
            || ') envoyé il y a ' || d.days_since_sent
            || ' jours sans relance, montant : ' || d.total || ' MAD.',
        'medium'
    FROM agent_reporting.fn_devis_pending_followup() d

    UNION ALL

    -- 4. Clients en retard de paiement récurrent
    SELECT
        'client_recurring_late',
        c.client_id::text,
        c.recommendation,
        CASE WHEN c.late_occurrences >= 4 THEN 'high' ELSE 'medium' END
    FROM agent_reporting.fn_recurring_late_clients() c

    UNION ALL

    -- 5. Alertes de paiement par vente (impayé / partiel)
    SELECT
        'sale_payment_' || s.alert_type,
        s.sale_id::text,
        s.alert_message,
        CASE WHEN s.days_elapsed >= 60 THEN 'high' ELSE 'medium' END
    FROM agent_reporting.fn_sale_payment_alerts() s

    UNION ALL

    -- 6. Produits à discontinuer (marge négative / stock dormant)
    SELECT
        'product_discontinue',
        p.product_id::text,
        'Produit "' || p.product_name || '" à discontinuer : ' || p.discontinue_reason
            || ' (marge : ' || COALESCE(p.margin::text, 'N/A') || ' MAD).',
        CASE WHEN p.margin < 0 THEN 'high' ELSE 'low' END
    FROM agent_reporting.fn_products_to_discontinue() p

    UNION ALL

    -- 7. Suggestions de réapprovisionnement (stock sous seuil)
    SELECT
        'reorder_suggestion',
        p.product_id::text,
        'Stock bas pour "' || p.product_name || '" (' || p.current_stock
            || ' restant, seuil : ' || p.alert_stock_threshold
            || '). Quantité suggérée à commander : ' || p.suggested_reorder_qty || '.',
        CASE
            WHEN p.days_until_stockout IS NOT NULL AND p.days_until_stockout <= 7 THEN 'high'
            ELSE 'medium'
        END
    FROM agent_reporting.fn_reorder_suggestions() p

    UNION ALL

    -- 8. Produits à taux de retour anormalement élevé
    SELECT
        'product_high_return_rate',
        p.product_id::text,
        'Produit "' || p.product_name || '" a un taux de retour de '
            || p.refund_rate_pct || '% (' || p.quantity_refunded || ' unité(s) retournée(s) sur '
            || p.quantity_sold || ' vendues).',
        CASE WHEN p.refund_rate_pct >= 25 THEN 'high' ELSE 'medium' END
    FROM agent_reporting.fn_products_high_return_rate() p

    UNION ALL

    -- 9. Baisse significative des ventes par produit
    --    Convention par défaut : période actuelle = 30 derniers jours,
    --    période précédente = les 30 jours d'avant.
    SELECT
        'sales_decline',
        p.product_id::text,
        'Baisse des ventes pour "' || p.product_name || '" : ' || p.variation_pct
            || '% (' || p.previous_qty || ' -> ' || p.current_qty || ' unités) sur les 30 derniers jours.',
        LOWER(p.alert_level)
    FROM agent_reporting.fn_sales_alert_decline(
        (CURRENT_DATE - INTERVAL '30 days')::date,
        CURRENT_DATE::date,
        (CURRENT_DATE - INTERVAL '60 days')::date,
        (CURRENT_DATE - INTERVAL '31 days')::date
    ) p;

END;
$$;

