-- ---- [2/64] sales/consultation/v_sales_detail.sql

CREATE OR REPLACE VIEW agent_reporting.v_sales_detail AS

SELECT
    -------------------------------------------------------
    -- Informations de la vente
    -------------------------------------------------------
    s.id AS sale_id,
    s.reference AS sale_reference,
    s.created_at AS sale_date,
    s.updated_at AS sale_updated_at,
    s.status,

    -------------------------------------------------------
    -- Montants
    -------------------------------------------------------
    s.subtotal,
    s.tax_rate,
    s.tax_amount,
    s.discount_amount,

    -- Montant initial de la vente
    (s.subtotal + s.tax_amount - s.discount_amount) AS gross_total,

    -- Montant remboursé
    COALESCE(r.refunded_total, 0) AS refunded_total,

    -- Montant réellement conservé
    (
        (s.subtotal + s.tax_amount - s.discount_amount)
        - COALESCE(r.refunded_total, 0)
    ) AS net_total,

    -------------------------------------------------------
    -- Informations du client
    -------------------------------------------------------
    c.id AS client_id,
    c.name AS client_name,
    c.email AS client_email,
    c.phone AS client_phone,
    c.address AS client_address

FROM public.sales s

INNER JOIN public.clients c
    ON s.client_id = c.id

LEFT JOIN (
    SELECT
        sale_id,
        SUM(refund_total) AS refunded_total
    FROM public.sale_items
    GROUP BY sale_id
) r
ON s.id = r.sale_id;

