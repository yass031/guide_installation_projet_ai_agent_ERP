-- ---- [52/64] payments/recommandation/fn_cashflow_forecast.sql
CREATE OR REPLACE FUNCTION agent_reporting.fn_cashflow_forecast(days_ahead integer DEFAULT 30)
 RETURNS TABLE(
    total_outstanding numeric,
    avg_daily_collection_last_30d numeric,
    projected_collection numeric,
    projection_confidence text,
    forecast_message text
 )
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_outstanding numeric;
    v_avg_daily numeric;
    v_projected numeric;
    v_confidence text;
BEGIN
    -- 1. Solde total restant dû, toutes ventes non soldées confondues
    SELECT COALESCE(SUM(sd.net_total - COALESCE(pd.applied, 0)), 0)
    INTO v_outstanding
    FROM agent_reporting.v_sales_detail sd
    LEFT JOIN (
        SELECT
            pa.payable_id AS sale_id,
            SUM(pa.amount_applied) AS applied
        FROM payment_allocations pa
        JOIN payments p ON p.id = pa.payment_id AND p.status = 'approved'
        WHERE pa.payable_type LIKE '%Sale'
        GROUP BY pa.payable_id
    ) pd ON pd.sale_id = sd.sale_id
    WHERE sd.net_total - COALESCE(pd.applied, 0) > 0;

    -- 2. Moyenne encaissée par jour sur les 30 derniers jours (vélocité récente)
    SELECT COALESCE(SUM(pa.amount_applied), 0) / 30.0
    INTO v_avg_daily
    FROM payment_allocations pa
    JOIN payments p ON p.id = pa.payment_id AND p.status = 'approved'
    WHERE pa.payable_type LIKE '%Sale'
      AND pa.created_at >= CURRENT_DATE - INTERVAL '30 days';

    -- 3. Projection = vélocité récente x jours à venir, plafonnée par le solde total dû
    v_projected := LEAST(v_avg_daily * days_ahead, v_outstanding);

    -- 4. Confiance basse si peu d'historique récent pour appuyer la projection
    v_confidence := CASE
        WHEN v_avg_daily = 0 THEN 'faible'
        WHEN v_avg_daily * 30 < v_outstanding * 0.1 THEN 'faible'
        ELSE 'moyenne'
    END;

    RETURN QUERY
    SELECT
        v_outstanding,
        ROUND(v_avg_daily, 2),
        ROUND(v_projected, 2),
        v_confidence,
        'Solde total restant dû : ' || v_outstanding || ' MAD. Sur la base du rythme '
            || 'd''encaissement des 30 derniers jours (' || ROUND(v_avg_daily, 2)
            || ' MAD/jour), environ ' || ROUND(v_projected, 2)
            || ' MAD pourraient être encaissés dans les ' || days_ahead
            || ' prochains jours (confiance : ' || v_confidence || ').';
END;
$function$;

-- ---- [53/64] payments/recommandation/fn_recurring_late_clients.sql
-- ----------------------------------------------------------------
-- fn_recurring_late_clients
-- Clients récidivistes : plusieurs ventes en retard (seuil dépassé)
-- avec un solde restant > 0, que ce soit rien payé OU partiellement
-- payé (option B validée avec l'utilisateur)
-- ----------------------------------------------------------------
CREATE OR REPLACE FUNCTION agent_reporting.fn_recurring_late_clients(threshold_days integer DEFAULT 30, min_occurrences integer DEFAULT 2)
 RETURNS TABLE(client_id bigint, client_name text, client_phone text, client_email text, late_occurrences bigint, fully_unpaid_count bigint, partially_paid_count bigint, total_unpaid_amount numeric, concerned_sales text, recommendation text)
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH unpaid_flags AS (
        SELECT
            sd.sale_id,
            sd.sale_reference,
            sd.client_id,
            sd.client_name::text AS client_name,
            sd.client_phone::text AS client_phone,
            sd.client_email::text AS client_email,
            sd.net_total,
            (CURRENT_DATE - sd.sale_date::date) AS days_elapsed,
            COALESCE(SUM(pa.amount_applied), 0)  AS total_paid,
            sd.net_total - COALESCE(SUM(pa.amount_applied), 0) AS remaining
        FROM agent_reporting.v_sales_detail sd
        LEFT JOIN payment_allocations pa
            ON pa.payable_id = sd.sale_id
            AND pa.payable_type LIKE '%Sale'
        LEFT JOIN payments p
            ON p.id = pa.payment_id
            AND p.status = 'approved'
        GROUP BY sd.sale_id, sd.sale_reference, sd.client_id, sd.client_name, sd.client_phone, sd.client_email, sd.net_total, sd.sale_date
        HAVING sd.net_total - COALESCE(SUM(pa.amount_applied), 0) > 0
           AND (CURRENT_DATE - sd.sale_date::date) >= threshold_days
    )
    SELECT
        uf.client_id,
        MAX(uf.client_name),
        MAX(uf.client_phone),
        MAX(uf.client_email),
        COUNT(*)                                                            AS late_occurrences,
        COUNT(*) FILTER (WHERE uf.total_paid = 0)                          AS fully_unpaid_count,
        COUNT(*) FILTER (WHERE uf.total_paid > 0)                          AS partially_paid_count,
        SUM(uf.remaining)                                                   AS total_unpaid_amount,
        STRING_AGG(uf.sale_reference, ', ' ORDER BY uf.sale_reference)     AS concerned_sales,
        'Client en retard récurrent : ' || COUNT(*) || ' vente(s) en retard de plus de '
            || threshold_days || ' jours (dont ' || COUNT(*) FILTER (WHERE uf.total_paid = 0)
            || ' totalement impayée(s)), solde restant total : ' || SUM(uf.remaining)
            || ' MAD. À surveiller de près.'                                AS recommendation
    FROM unpaid_flags uf
    GROUP BY uf.client_id
    HAVING COUNT(*) >= min_occurrences
    ORDER BY late_occurrences DESC, total_unpaid_amount DESC;
END;
$function$;

